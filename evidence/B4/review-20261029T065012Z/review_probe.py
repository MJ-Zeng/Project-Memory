def sign_bytes(payload: bytes, key=None) -> bytes:
    pf = Path(tempfile.mkdtemp(dir=WORK)) / 'p.bin'
    sf = pf.with_suffix('.sig')
    pf.write_bytes(payload)
    sh([OPENSSL, 'dgst', '-sha256', '-sign', str(key or KEY), '-out', str(sf), str(pf)])
    return sf.read_bytes()


